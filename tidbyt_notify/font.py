GLYPH_HEIGHT = 5
TRACKING = 1  # blank columns between glyphs


def _glyph(ch):
    return GLYPHS.get(ch.upper(), GLYPHS["?"])


def text_width(text):
    """Pixel width of a string, including inter-glyph tracking."""
    if not text:
        return 0
    return sum(len(_glyph(c)[0]) + TRACKING for c in text) - TRACKING


def draw_text(draw, xy, text, fill):
    """Draw text with the pixel font onto a PIL ImageDraw. Returns end x."""
    x, y = xy
    for ch in text:
        rows = _glyph(ch)
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit == "1":
                    draw.point((x + rx, y + ry), fill=fill)
        x += len(rows[0]) + TRACKING
    return x


def wrap(text, max_width):
    """Greedy word-wrap to a pixel width. Long words are hard-broken."""
    lines = []
    current = ""
    for word in text.split():
        while text_width(word) > max_width:
            # hard-break a word that can't fit on any line
            if current:
                lines.append(current)
                current = ""
            cut = len(word)
            while cut > 1 and text_width(word[:cut]) > max_width:
                cut -= 1
            lines.append(word[:cut])
            word = word[cut:]
        candidate = (current + " " + word).strip()
        if text_width(candidate) <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines
